ALTER TABLE result_issue_requests
    ADD COLUMN attachment_upload_token_hash VARCHAR(64),
    ADD COLUMN attachment_upload_token_expires_at TIMESTAMPTZ,
    ADD CONSTRAINT ck_result_issue_attachment_token
        CHECK (
            (attachment_upload_token_hash IS NULL AND attachment_upload_token_expires_at IS NULL)
            OR
            (char_length(attachment_upload_token_hash) = 64 AND attachment_upload_token_expires_at IS NOT NULL)
        );

CREATE TABLE result_issue_attachments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_request_id BIGINT NOT NULL REFERENCES result_issue_requests(id) ON DELETE CASCADE,
    original_file_name VARCHAR(512) NOT NULL,
    storage_key VARCHAR(768) NOT NULL,
    content_type VARCHAR(255),
    detected_content_type VARCHAR(255),
    size_bytes BIGINT NOT NULL,
    storage_etag VARCHAR(512),
    upload_status VARCHAR(32) NOT NULL DEFAULT 'PENDING_UPLOAD',
    scan_status VARCHAR(32) NOT NULL DEFAULT 'PENDING',
    upload_authorization_expires_at TIMESTAMPTZ NOT NULL,
    retention_expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    uploaded_at TIMESTAMPTZ,
    scanned_at TIMESTAMPTZ,
    deleted_at TIMESTAMPTZ,
    CONSTRAINT uk_result_issue_attachment_storage_key UNIQUE (storage_key),
    CONSTRAINT ck_result_issue_attachment_name
        CHECK (btrim(original_file_name) <> '' AND char_length(original_file_name) <= 512),
    CONSTRAINT ck_result_issue_attachment_size
        CHECK (size_bytes > 0),
    CONSTRAINT ck_result_issue_attachment_upload_status
        CHECK (upload_status IN ('PENDING_UPLOAD', 'UPLOADED', 'UPLOAD_FAILED', 'DELETED')),
    CONSTRAINT ck_result_issue_attachment_scan_status
        CHECK (scan_status IN ('PENDING', 'CLEAN', 'INFECTED', 'SCAN_FAILED')),
    CONSTRAINT ck_result_issue_attachment_uploaded
        CHECK (upload_status <> 'UPLOADED' OR uploaded_at IS NOT NULL),
    CONSTRAINT ck_result_issue_attachment_scanned
        CHECK (scan_status = 'PENDING' OR scanned_at IS NOT NULL),
    CONSTRAINT ck_result_issue_attachment_deleted
        CHECK (upload_status <> 'DELETED' OR deleted_at IS NOT NULL)
);

CREATE INDEX ix_result_issue_attachment_issue_created
    ON result_issue_attachments(issue_request_id, created_at, id);

CREATE INDEX ix_result_issue_attachment_scan_queue
    ON result_issue_attachments(scan_status, created_at, id)
    WHERE upload_status = 'UPLOADED' AND scan_status IN ('PENDING', 'SCAN_FAILED');

CREATE INDEX ix_result_issue_attachment_retention
    ON result_issue_attachments(retention_expires_at, id)
    WHERE upload_status <> 'DELETED';
