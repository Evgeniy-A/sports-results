CREATE TABLE events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    slug VARCHAR(160) NOT NULL,
    starts_at TIMESTAMPTZ,
    ends_at TIMESTAMPTZ,
    location VARCHAR(255),
    publication_status VARCHAR(32) NOT NULL DEFAULT 'DRAFT',
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_events_slug UNIQUE (slug),
    CONSTRAINT ck_events_dates CHECK (ends_at IS NULL OR starts_at IS NULL OR ends_at >= starts_at),
    CONSTRAINT ck_events_publication_status CHECK (publication_status IN ('DRAFT', 'PUBLISHED', 'ARCHIVED'))
);

CREATE TABLE races (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES events(id),
    source_code VARCHAR(255) NOT NULL,
    name VARCHAR(255) NOT NULL,
    slug VARCHAR(160) NOT NULL,
    distance_meters NUMERIC(12,3),
    starts_at TIMESTAMPTZ,
    entry_mode VARCHAR(32) NOT NULL DEFAULT 'UNKNOWN',
    display_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_races_event_source_code UNIQUE (event_id, source_code),
    CONSTRAINT uk_races_event_slug UNIQUE (event_id, slug),
    CONSTRAINT uk_races_id_event UNIQUE (id, event_id),
    CONSTRAINT ck_races_distance CHECK (distance_meters IS NULL OR distance_meters >= 0),
    CONSTRAINT ck_races_display_order CHECK (display_order >= 0),
    CONSTRAINT ck_races_entry_mode CHECK (entry_mode IN ('INDIVIDUAL', 'TEAM', 'MIXED', 'UNKNOWN'))
);

CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    race_id BIGINT NOT NULL REFERENCES races(id),
    source_name VARCHAR(255) NOT NULL,
    display_name VARCHAR(255) NOT NULL,
    display_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_categories_race_source_name UNIQUE (race_id, source_name),
    CONSTRAINT uk_categories_id_race UNIQUE (id, race_id),
    CONSTRAINT ck_categories_display_order CHECK (display_order >= 0)
);

CREATE TABLE import_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES events(id),
    race_id BIGINT,
    scope_type VARCHAR(16) NOT NULL,
    source_filename VARCHAR(255) NOT NULL,
    file_sha256 VARCHAR(64) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'PENDING',
    total_rows INTEGER NOT NULL DEFAULT 0,
    imported_rows INTEGER NOT NULL DEFAULT 0,
    skipped_rows INTEGER NOT NULL DEFAULT 0,
    failed_rows INTEGER NOT NULL DEFAULT 0,
    error_summary JSONB,
    started_at TIMESTAMPTZ NOT NULL,
    finished_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_import_batches_race_event FOREIGN KEY (race_id, event_id) REFERENCES races(id, event_id),
    CONSTRAINT ck_import_batches_scope CHECK (
        (scope_type = 'EVENT' AND race_id IS NULL)
        OR (scope_type = 'RACE' AND race_id IS NOT NULL)
    ),
    CONSTRAINT ck_import_batches_status CHECK (status IN ('PENDING', 'VALIDATING', 'SUCCEEDED', 'FAILED')),
    CONSTRAINT ck_import_batches_file_hash CHECK (file_sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_import_batches_counts CHECK (
        total_rows >= 0 AND imported_rows >= 0 AND skipped_rows >= 0 AND failed_rows >= 0
    )
);

CREATE TABLE registrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    race_id BIGINT NOT NULL REFERENCES races(id),
    category_id BIGINT,
    import_batch_id BIGINT NOT NULL REFERENCES import_batches(id),
    entry_kind VARCHAR(32) NOT NULL DEFAULT 'UNKNOWN',
    bib VARCHAR(64),
    display_name VARCHAR(320) NOT NULL,
    first_name VARCHAR(160),
    last_name VARCHAR(160),
    birth_date DATE,
    gender VARCHAR(32),
    source_row_number INTEGER NOT NULL,
    source_row_hash VARCHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_registrations_category_race FOREIGN KEY (category_id, race_id) REFERENCES categories(id, race_id),
    CONSTRAINT uk_registrations_batch_row UNIQUE (import_batch_id, source_row_number),
    CONSTRAINT ck_registrations_entry_kind CHECK (entry_kind IN ('PERSON', 'TEAM', 'OTHER', 'UNKNOWN')),
    CONSTRAINT ck_registrations_source_row CHECK (source_row_number > 0),
    CONSTRAINT ck_registrations_source_hash CHECK (source_row_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_registrations_identity CHECK (btrim(display_name) <> '' OR bib IS NOT NULL)
);

CREATE TABLE results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_id BIGINT NOT NULL REFERENCES registrations(id),
    status VARCHAR(64) NOT NULL,
    gun_time_ms BIGINT,
    chip_time_ms BIGINT,
    overall_place INTEGER,
    gender_place INTEGER,
    category_place INTEGER,
    net_overall_place INTEGER,
    net_gender_place INTEGER,
    net_category_place INTEGER,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_results_registration UNIQUE (registration_id),
    CONSTRAINT ck_results_status CHECK (btrim(status) <> ''),
    CONSTRAINT ck_results_times CHECK (
        (gun_time_ms IS NULL OR gun_time_ms >= 0)
        AND (chip_time_ms IS NULL OR chip_time_ms >= 0)
    ),
    CONSTRAINT ck_results_places CHECK (
        (overall_place IS NULL OR overall_place > 0)
        AND (gender_place IS NULL OR gender_place > 0)
        AND (category_place IS NULL OR category_place > 0)
        AND (net_overall_place IS NULL OR net_overall_place > 0)
        AND (net_gender_place IS NULL OR net_gender_place > 0)
        AND (net_category_place IS NULL OR net_category_place > 0)
    )
);

CREATE TABLE checkpoints (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    race_id BIGINT NOT NULL REFERENCES races(id),
    code VARCHAR(100) NOT NULL,
    name VARCHAR(255) NOT NULL,
    sequence_number INTEGER NOT NULL,
    distance_meters NUMERIC(12,3),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_checkpoints_race_code UNIQUE (race_id, code),
    CONSTRAINT uk_checkpoints_race_sequence UNIQUE (race_id, sequence_number),
    CONSTRAINT ck_checkpoints_sequence CHECK (sequence_number > 0),
    CONSTRAINT ck_checkpoints_distance CHECK (distance_meters IS NULL OR distance_meters >= 0)
);

CREATE TABLE splits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    result_id BIGINT NOT NULL REFERENCES results(id),
    checkpoint_id BIGINT NOT NULL REFERENCES checkpoints(id),
    gun_time_ms BIGINT,
    chip_time_ms BIGINT,
    overall_place INTEGER,
    gender_place INTEGER,
    category_place INTEGER,
    net_overall_place INTEGER,
    net_gender_place INTEGER,
    net_category_place INTEGER,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_splits_result_checkpoint UNIQUE (result_id, checkpoint_id),
    CONSTRAINT ck_splits_times CHECK (
        (gun_time_ms IS NULL OR gun_time_ms >= 0)
        AND (chip_time_ms IS NULL OR chip_time_ms >= 0)
    ),
    CONSTRAINT ck_splits_places CHECK (
        (overall_place IS NULL OR overall_place > 0)
        AND (gender_place IS NULL OR gender_place > 0)
        AND (category_place IS NULL OR category_place > 0)
        AND (net_overall_place IS NULL OR net_overall_place > 0)
        AND (net_gender_place IS NULL OR net_gender_place > 0)
        AND (net_category_place IS NULL OR net_category_place > 0)
    ),
    CONSTRAINT ck_splits_has_metric CHECK (
        gun_time_ms IS NOT NULL OR chip_time_ms IS NOT NULL
        OR overall_place IS NOT NULL OR gender_place IS NOT NULL OR category_place IS NOT NULL
        OR net_overall_place IS NOT NULL OR net_gender_place IS NOT NULL OR net_category_place IS NOT NULL
    )
);

CREATE INDEX ix_races_event_order ON races(event_id, display_order);
CREATE INDEX ix_categories_race_order ON categories(race_id, display_order);
CREATE INDEX ix_import_batches_event_started ON import_batches(event_id, started_at DESC);
CREATE INDEX ix_import_batches_event_hash ON import_batches(event_id, file_sha256);
CREATE INDEX ix_registrations_race_bib ON registrations(race_id, bib);
CREATE INDEX ix_registrations_race_category ON registrations(race_id, category_id);
CREATE INDEX ix_registrations_import_batch ON registrations(import_batch_id);
CREATE INDEX ix_registrations_name ON registrations(race_id, lower(last_name), lower(first_name));
CREATE INDEX ix_results_status ON results(status);
CREATE INDEX ix_results_gun_time ON results(gun_time_ms);
CREATE INDEX ix_results_chip_time ON results(chip_time_ms);
CREATE INDEX ix_results_overall_place ON results(overall_place);
CREATE INDEX ix_results_net_overall_place ON results(net_overall_place);
CREATE INDEX ix_splits_checkpoint_chip_time ON splits(checkpoint_id, chip_time_ms);
