CREATE TABLE event_series (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    slug VARCHAR(160) NOT NULL,
    description TEXT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_event_series_slug UNIQUE (slug),
    CONSTRAINT ck_event_series_name CHECK (btrim(name) <> ''),
    CONSTRAINT ck_event_series_slug CHECK (btrim(slug) <> '')
);

INSERT INTO event_series(name, slug, active, created_at, updated_at)
SELECT 'M52', 'm52', TRUE, min(created_at), max(updated_at)
FROM events
WHERE lower(name) = 'm52 2025' OR slug = 'm52-2025'
HAVING count(*) > 0;

INSERT INTO event_series(name, slug, active, created_at, updated_at)
SELECT event.name, 'legacy-event-' || event.id, TRUE, event.created_at, event.updated_at
FROM events event
WHERE NOT (lower(event.name) = 'm52 2025' OR event.slug = 'm52-2025');

ALTER TABLE events ADD COLUMN event_series_id BIGINT;

UPDATE events
SET event_series_id = (SELECT id FROM event_series WHERE slug = 'm52')
WHERE lower(name) = 'm52 2025' OR slug = 'm52-2025';

UPDATE events
SET event_series_id = series.id
FROM event_series series
WHERE series.slug = 'legacy-event-' || events.id
  AND events.event_series_id IS NULL;

ALTER TABLE events
    ALTER COLUMN event_series_id SET NOT NULL,
    ADD CONSTRAINT fk_events_event_series FOREIGN KEY (event_series_id) REFERENCES event_series(id);

CREATE TABLE award_policies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    race_id BIGINT NOT NULL,
    ranking_basis VARCHAR(32) NOT NULL,
    primary_standing_mode VARCHAR(32) NOT NULL,
    absolute_prize_places INTEGER NOT NULL,
    category_enabled BOOLEAN NOT NULL,
    category_prize_places INTEGER NOT NULL,
    exclude_absolute_winners_from_category BOOLEAN NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_award_policies_race UNIQUE (race_id),
    CONSTRAINT fk_award_policies_race FOREIGN KEY (race_id) REFERENCES races(id) ON DELETE CASCADE,
    CONSTRAINT ck_award_policies_ranking_basis CHECK (ranking_basis IN ('GUN_TIME', 'CHIP_TIME')),
    CONSTRAINT ck_award_policies_primary_mode CHECK (primary_standing_mode IN ('ALL', 'BY_GENDER', 'NONE')),
    CONSTRAINT ck_award_policies_places CHECK (absolute_prize_places >= 0 AND category_prize_places >= 0)
);

