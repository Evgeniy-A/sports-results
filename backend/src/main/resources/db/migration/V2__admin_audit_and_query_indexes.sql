CREATE TABLE admin_change_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor VARCHAR(160) NOT NULL,
    changed_at TIMESTAMPTZ NOT NULL,
    entity_type VARCHAR(32) NOT NULL,
    entity_id BIGINT NOT NULL,
    field_name VARCHAR(100) NOT NULL,
    old_value TEXT,
    new_value TEXT,
    CONSTRAINT ck_admin_change_logs_actor CHECK (btrim(actor) <> ''),
    CONSTRAINT ck_admin_change_logs_entity_type CHECK (entity_type IN ('REGISTRATION', 'RESULT')),
    CONSTRAINT ck_admin_change_logs_field_name CHECK (btrim(field_name) <> '')
);

CREATE INDEX ix_admin_change_logs_entity
    ON admin_change_logs(entity_type, entity_id, changed_at DESC);
CREATE INDEX ix_admin_change_logs_actor_changed
    ON admin_change_logs(actor, changed_at DESC);

CREATE INDEX ix_registrations_race_gender
    ON registrations(race_id, lower(gender))
    WHERE gender IS NOT NULL;

CREATE UNIQUE INDEX uk_import_batches_successful_event_file
    ON import_batches(event_id, file_sha256)
    WHERE scope_type = 'EVENT' AND status = 'SUCCEEDED';
