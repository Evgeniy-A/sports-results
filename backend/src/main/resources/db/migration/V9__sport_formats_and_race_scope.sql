CREATE TABLE sport_formats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES events(id),
    code VARCHAR(100),
    source_name VARCHAR(255),
    display_name VARCHAR(255) NOT NULL,
    display_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_sport_formats_id_event UNIQUE (id, event_id),
    CONSTRAINT ck_sport_formats_code CHECK (code IS NULL OR btrim(code) <> ''),
    CONSTRAINT ck_sport_formats_source_name CHECK (source_name IS NULL OR btrim(source_name) <> ''),
    CONSTRAINT ck_sport_formats_display_name CHECK (btrim(display_name) <> ''),
    CONSTRAINT ck_sport_formats_display_order CHECK (display_order >= 0)
);

CREATE UNIQUE INDEX uk_sport_formats_event_code
    ON sport_formats (event_id, code)
    WHERE code IS NOT NULL;

CREATE UNIQUE INDEX uk_sport_formats_event_source_name
    ON sport_formats (event_id, source_name)
    WHERE source_name IS NOT NULL;

CREATE INDEX ix_sport_formats_event_order
    ON sport_formats (event_id, display_order, id);

INSERT INTO sport_formats (
    event_id, code, source_name, display_name, display_order, created_at, updated_at
)
SELECT id, 'default', NULL, 'Основной формат', 0, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
FROM events;

ALTER TABLE races
    ADD COLUMN sport_format_id BIGINT;

UPDATE races race
SET sport_format_id = format.id
FROM sport_formats format
WHERE format.event_id = race.event_id
  AND format.code = 'default';

