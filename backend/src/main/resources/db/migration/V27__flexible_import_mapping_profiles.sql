ALTER TABLE import_operations
    ADD COLUMN input_config JSONB NOT NULL DEFAULT '{}'::jsonb;

CREATE TABLE import_mapping_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL,
    file_type VARCHAR(16) NOT NULL,
    header_signature VARCHAR(64) NOT NULL,
    mapping_json JSONB NOT NULL,
    race_discriminator_header VARCHAR(255),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_import_mapping_profiles_name CHECK (btrim(name) <> ''),
    CONSTRAINT ck_import_mapping_profiles_file_type CHECK (file_type IN ('CSV', 'XLSX')),
    CONSTRAINT ck_import_mapping_profiles_signature CHECK (header_signature ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_import_mapping_profiles_mapping_object CHECK (jsonb_typeof(mapping_json) = 'object')
);

CREATE UNIQUE INDEX uk_import_mapping_profiles_name_ci
    ON import_mapping_profiles (lower(name));

CREATE INDEX ix_import_mapping_profiles_signature
    ON import_mapping_profiles (file_type, header_signature, updated_at DESC);
