CREATE TABLE event_series_start_templates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_series_id BIGINT NOT NULL REFERENCES event_series(id) ON DELETE CASCADE,
    name VARCHAR(255) NOT NULL,
    distance_meters NUMERIC(12,3),
    display_order INTEGER NOT NULL DEFAULT 0,
    public_visible BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_event_series_start_templates_name CHECK (btrim(name) <> ''),
    CONSTRAINT ck_event_series_start_templates_distance CHECK (
        distance_meters IS NULL OR distance_meters >= 0
    ),
    CONSTRAINT ck_event_series_start_templates_display_order CHECK (display_order >= 0)
);

CREATE INDEX ix_event_series_start_templates_order
    ON event_series_start_templates (event_series_id, display_order, id);

CREATE TABLE event_series_start_award_policy_templates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_start_id BIGINT NOT NULL,
    ranking_basis VARCHAR(32) NOT NULL,
    primary_standing_mode VARCHAR(32) NOT NULL,
    absolute_prize_places INTEGER NOT NULL,
    category_enabled BOOLEAN NOT NULL,
    age_calculation_mode VARCHAR(32) NOT NULL,
    category_prize_places INTEGER NOT NULL,
    exclude_absolute_winners_from_category BOOLEAN NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_event_series_start_award_policy_templates_start UNIQUE (template_start_id),
    CONSTRAINT fk_event_series_start_award_policy_templates_start
        FOREIGN KEY (template_start_id) REFERENCES event_series_start_templates(id) ON DELETE CASCADE,
    CONSTRAINT ck_event_series_start_award_policy_templates_ranking_basis
        CHECK (ranking_basis IN ('GUN_TIME', 'CHIP_TIME', 'NONE')),
    CONSTRAINT ck_event_series_start_award_policy_templates_primary_mode
        CHECK (primary_standing_mode IN ('ALL', 'BY_GENDER', 'NONE')),
    CONSTRAINT ck_event_series_start_award_policy_templates_age_mode
        CHECK (age_calculation_mode IN ('EVENT_DATE', 'END_OF_EVENT_YEAR')),
    CONSTRAINT ck_event_series_start_award_policy_templates_places
        CHECK (absolute_prize_places >= 0 AND category_prize_places >= 0),
    CONSTRAINT ck_event_series_start_award_policy_templates_none_consistency
        CHECK (
            ranking_basis <> 'NONE'
            OR (
                primary_standing_mode = 'NONE'
                AND absolute_prize_places = 0
                AND category_enabled = FALSE
                AND category_prize_places = 0
                AND exclude_absolute_winners_from_category = FALSE
            )
        )
);

CREATE TABLE event_series_start_category_templates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_start_id BIGINT NOT NULL,
    source_name VARCHAR(255) NOT NULL,
    display_name VARCHAR(255) NOT NULL,
    display_order INTEGER NOT NULL DEFAULT 0,
    min_age INTEGER,
    max_age INTEGER,
    gender VARCHAR(16),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_event_series_start_category_templates_source
        UNIQUE (template_start_id, source_name),
    CONSTRAINT fk_event_series_start_category_templates_start
        FOREIGN KEY (template_start_id) REFERENCES event_series_start_templates(id) ON DELETE CASCADE,
    CONSTRAINT ck_event_series_start_category_templates_source_name CHECK (btrim(source_name) <> ''),
    CONSTRAINT ck_event_series_start_category_templates_display_name CHECK (btrim(display_name) <> ''),
    CONSTRAINT ck_event_series_start_category_templates_display_order CHECK (display_order >= 0),
    CONSTRAINT ck_event_series_start_category_templates_age_range CHECK (
        (min_age IS NULL AND max_age IS NULL)
        OR (min_age IS NOT NULL AND min_age >= 0 AND (max_age IS NULL OR max_age >= min_age))
    ),
    CONSTRAINT ck_event_series_start_category_templates_gender
        CHECK (gender IS NULL OR gender IN ('MALE', 'FEMALE'))
);

CREATE INDEX ix_event_series_start_category_templates_order
    ON event_series_start_category_templates (template_start_id, display_order, id);

CREATE INDEX ix_event_series_start_category_templates_age
    ON event_series_start_category_templates (template_start_id, enabled, gender, min_age, max_age);
