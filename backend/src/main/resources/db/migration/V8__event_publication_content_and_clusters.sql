    ADD COLUMN results_publication_status VARCHAR(32) NOT NULL DEFAULT 'DRAFT';

UPDATE events
SET results_publication_status = 'PUBLISHED'
WHERE publication_status = 'PUBLISHED';

ALTER TABLE events
    ADD CONSTRAINT ck_events_time_zone CHECK (btrim(time_zone) <> ''),
    ADD CONSTRAINT ck_events_results_publication_status
        CHECK (results_publication_status IN ('DRAFT', 'PUBLISHED'));

CREATE TABLE event_participant_info (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES events(id),
    short_description TEXT,
    venue_name VARCHAR(255),
    venue_address VARCHAR(500),
    location_description TEXT,
    latitude NUMERIC(9,6),
    longitude NUMERIC(9,6),
    additional_info TEXT,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_event_participant_info_event UNIQUE (event_id),
    CONSTRAINT ck_event_participant_info_latitude CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_event_participant_info_longitude CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180)
);

CREATE TABLE event_info_blocks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES events(id),
    title VARCHAR(255) NOT NULL,
    content TEXT NOT NULL,
    display_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_event_info_blocks_title CHECK (btrim(title) <> ''),
    CONSTRAINT ck_event_info_blocks_content CHECK (btrim(content) <> ''),
    CONSTRAINT ck_event_info_blocks_display_order CHECK (display_order >= 0)
);

CREATE TABLE event_schedule_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES events(id),
    starts_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    ends_at TIMESTAMP WITHOUT TIME ZONE,
    title VARCHAR(255) NOT NULL,
    description TEXT,
    display_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_event_schedule_items_title CHECK (btrim(title) <> ''),
    CONSTRAINT ck_event_schedule_items_dates CHECK (ends_at IS NULL OR ends_at >= starts_at),
    CONSTRAINT ck_event_schedule_items_display_order CHECK (display_order >= 0)
);

CREATE TABLE event_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES events(id),
    type VARCHAR(32) NOT NULL,
    display_name VARCHAR(255) NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    storage_key VARCHAR(500) NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    size_bytes BIGINT NOT NULL,
    sha256 VARCHAR(64) NOT NULL,
    display_order INTEGER NOT NULL DEFAULT 0,
    is_public BOOLEAN NOT NULL DEFAULT TRUE,
    uploaded_at TIMESTAMPTZ NOT NULL,
    uploaded_by VARCHAR(160),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_event_documents_storage_key UNIQUE (storage_key),
    CONSTRAINT ck_event_documents_type CHECK (type IN ('PARTICIPANT_GUIDE', 'REGULATIONS', 'COURSE_MAP', 'PROGRAM', 'OTHER')),
    CONSTRAINT ck_event_documents_display_name CHECK (btrim(display_name) <> ''),
    CONSTRAINT ck_event_documents_original_filename CHECK (btrim(original_filename) <> ''),
    CONSTRAINT ck_event_documents_content_type CHECK (content_type = 'application/pdf'),
    CONSTRAINT ck_event_documents_size CHECK (size_bytes > 0),
    CONSTRAINT ck_event_documents_sha256 CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_event_documents_display_order CHECK (display_order >= 0)
);

CREATE TABLE start_clusters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    race_id BIGINT NOT NULL REFERENCES races(id),
    code VARCHAR(100),
    source_name VARCHAR(255),
    display_name VARCHAR(255) NOT NULL,
    display_order INTEGER NOT NULL DEFAULT 0,
    starts_at TIMESTAMP WITHOUT TIME ZONE,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_start_clusters_id_race UNIQUE (id, race_id),
    CONSTRAINT uk_start_clusters_race_display_name UNIQUE (race_id, display_name),
    CONSTRAINT ck_start_clusters_display_name CHECK (btrim(display_name) <> ''),
    CONSTRAINT ck_start_clusters_display_order CHECK (display_order >= 0)
);

CREATE UNIQUE INDEX uk_start_clusters_race_code
    ON start_clusters (race_id, code)
    WHERE code IS NOT NULL;

CREATE UNIQUE INDEX uk_start_clusters_race_source_name
    ON start_clusters (race_id, source_name)
    WHERE source_name IS NOT NULL;

ALTER TABLE registrations
    ADD COLUMN cluster_id BIGINT,
    ADD CONSTRAINT fk_registrations_cluster_race
        FOREIGN KEY (cluster_id, race_id) REFERENCES start_clusters(id, race_id);

CREATE INDEX ix_events_publication_local_date
    ON events (publication_status, starts_at, ends_at);
CREATE INDEX ix_event_schedule_event_start_order
    ON event_schedule_items (event_id, starts_at, display_order, id);
CREATE INDEX ix_event_info_blocks_event_order
    ON event_info_blocks (event_id, display_order, id);
CREATE INDEX ix_event_documents_event_order
    ON event_documents (event_id, display_order, id);
CREATE INDEX ix_start_clusters_race_order
    ON start_clusters (race_id, display_order, id);
CREATE INDEX ix_registrations_race_cluster
    ON registrations (race_id, cluster_id);

