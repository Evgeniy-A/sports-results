ALTER TABLE import_operations
    ADD COLUMN import_batch_id BIGINT REFERENCES import_batches(id),
    ADD COLUMN applied_by VARCHAR(160),
    ADD COLUMN applied_at TIMESTAMPTZ,
    ADD COLUMN inserted_count INTEGER,
    ADD COLUMN existing_skipped_count INTEGER,
    ADD COLUMN out_of_scope_count INTEGER,
    ADD COLUMN new_revision BIGINT,
    ADD CONSTRAINT uk_import_operations_import_batch UNIQUE (import_batch_id),
    ADD CONSTRAINT ck_import_operations_apply_counts CHECK (
        (inserted_count IS NULL OR inserted_count >= 0)
        AND (existing_skipped_count IS NULL OR existing_skipped_count >= 0)
        AND (out_of_scope_count IS NULL OR out_of_scope_count >= 0)
        AND (new_revision IS NULL OR new_revision >= 0)
    ),
    ADD CONSTRAINT ck_import_operations_applied_metadata CHECK (
        status <> 'APPLIED'
        OR (
            import_batch_id IS NOT NULL
            AND applied_by IS NOT NULL
            AND btrim(applied_by) <> ''
            AND applied_at IS NOT NULL
            AND inserted_count IS NOT NULL
            AND existing_skipped_count IS NOT NULL
            AND out_of_scope_count IS NOT NULL
            AND new_revision IS NOT NULL
        )
    );

CREATE TABLE import_operation_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id UUID NOT NULL REFERENCES import_operations(id) ON DELETE CASCADE,
    source_row_number INTEGER NOT NULL,
    bib VARCHAR(64),
    decision VARCHAR(32) NOT NULL,
    action VARCHAR(32) NOT NULL,
    -- Deliberately scalar: durable audit must survive the legacy Full Replace hard-delete path.
    registration_id BIGINT,
    result_id BIGINT,
    target_race_id BIGINT NOT NULL REFERENCES races(id),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_import_operation_items_row UNIQUE (operation_id, source_row_number),
    CONSTRAINT ck_import_operation_items_source_row CHECK (source_row_number > 0),
    CONSTRAINT ck_import_operation_items_decision CHECK (
        decision IN (
            'NEW', 'EXISTING_UNCHANGED', 'EXISTING_CHANGED', 'AMBIGUOUS',
            'CONFLICT', 'INVALID', 'DUPLICATE_IN_FILE', 'OUT_OF_SCOPE'
        )
    ),
    CONSTRAINT ck_import_operation_items_action CHECK (
        action IN ('INSERT', 'UPDATE', 'SKIP', 'BLOCKED')
    )
);

CREATE INDEX ix_import_operation_items_registration
    ON import_operation_items(registration_id)
    WHERE registration_id IS NOT NULL;
