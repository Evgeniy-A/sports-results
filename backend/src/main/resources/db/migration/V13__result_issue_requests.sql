ALTER TABLE results
    ADD CONSTRAINT uk_results_id_registration UNIQUE (id, registration_id);

CREATE TABLE result_issue_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES events(id),
    registration_id BIGINT NOT NULL REFERENCES registrations(id),
    result_id BIGINT,
    issue_type VARCHAR(32) NOT NULL,
    correction_reason VARCHAR(32),
    status VARCHAR(32) NOT NULL DEFAULT 'NEW',
    contact_email VARCHAR(320) NOT NULL,
    message TEXT NOT NULL,
    claimed_gun_time_ms BIGINT,
    claimed_chip_time_ms BIGINT,
    estimated_start_at TIMESTAMPTZ,
    estimated_finish_at TIMESTAMPTZ,
    observed_gun_time_ms BIGINT,
    observed_chip_time_ms BIGINT,
    observed_result_status VARCHAR(64),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    resolved_at TIMESTAMPTZ,
    CONSTRAINT fk_result_issue_result_registration
        FOREIGN KEY (result_id, registration_id) REFERENCES results(id, registration_id),
    CONSTRAINT ck_result_issue_type
        CHECK (issue_type IN ('MISSING_RESULT', 'RESULT_CORRECTION')),
    CONSTRAINT ck_result_issue_status
        CHECK (status IN ('NEW', 'IN_PROGRESS', 'RESOLVED', 'REJECTED')),
    CONSTRAINT ck_result_issue_correction_reason
        CHECK (correction_reason IS NULL OR correction_reason IN (
            'OFFICIAL_TIME', 'CHIP_TIME', 'RESULT_STATUS',
            'PARTICIPANT_DATA', 'RACE_OR_FORMAT', 'OTHER'
        )),
    CONSTRAINT ck_result_issue_email
        CHECK (btrim(contact_email) <> '' AND char_length(contact_email) <= 320),
    CONSTRAINT ck_result_issue_message
        CHECK (btrim(message) <> '' AND char_length(message) <= 4000),
    CONSTRAINT ck_result_issue_claimed_times
        CHECK (
            (claimed_gun_time_ms IS NULL OR claimed_gun_time_ms >= 0)
            AND (claimed_chip_time_ms IS NULL OR claimed_chip_time_ms >= 0)
        ),
    CONSTRAINT ck_result_issue_estimated_times
        CHECK (
            estimated_start_at IS NULL
            OR estimated_finish_at IS NULL
            OR estimated_finish_at >= estimated_start_at
        ),
    CONSTRAINT ck_result_issue_type_data
        CHECK (
            (
                issue_type = 'MISSING_RESULT'
                AND correction_reason IS NULL
                AND observed_gun_time_ms IS NULL
                AND observed_chip_time_ms IS NULL
                AND observed_result_status IS NULL
            )
            OR
            (
                issue_type = 'RESULT_CORRECTION'
                AND result_id IS NOT NULL
                AND correction_reason IS NOT NULL
                AND observed_result_status IS NOT NULL
            )
        ),
    CONSTRAINT ck_result_issue_resolution
        CHECK (status NOT IN ('NEW', 'IN_PROGRESS') OR resolved_at IS NULL)
);

CREATE UNIQUE INDEX uk_result_issue_active_registration_type
    ON result_issue_requests(registration_id, issue_type)
    WHERE status IN ('NEW', 'IN_PROGRESS');

CREATE INDEX ix_result_issue_event_status_created
    ON result_issue_requests(event_id, status, created_at DESC);

CREATE INDEX ix_result_issue_event_type_created
    ON result_issue_requests(event_id, issue_type, created_at DESC);

CREATE INDEX ix_result_issue_registration_created
    ON result_issue_requests(registration_id, created_at DESC);
