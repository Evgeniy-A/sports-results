    ADD COLUMN results_publication_status VARCHAR(32) NOT NULL DEFAULT 'DRAFT';

UPDATE races race
SET results_publication_status = event.results_publication_status
FROM events event
WHERE event.id = race.event_id;

ALTER TABLE races
    ADD CONSTRAINT ck_races_results_publication_status
        CHECK (results_publication_status IN ('DRAFT', 'PUBLISHED'));

CREATE TABLE race_result_publication_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    race_id BIGINT NOT NULL REFERENCES races(id),
    from_status VARCHAR(32) NOT NULL,
    to_status VARCHAR(32) NOT NULL,
    actor VARCHAR(160) NOT NULL,
    reason VARCHAR(1000),
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_race_result_publication_history_from_status
        CHECK (from_status IN ('DRAFT', 'PUBLISHED')),
    CONSTRAINT ck_race_result_publication_history_to_status
        CHECK (to_status IN ('DRAFT', 'PUBLISHED')),
    CONSTRAINT ck_race_result_publication_history_transition
        CHECK (from_status <> to_status),
    CONSTRAINT ck_race_result_publication_history_actor
        CHECK (btrim(actor) <> ''),
    CONSTRAINT ck_race_result_publication_history_reason
        CHECK (reason IS NULL OR btrim(reason) <> '')
);

CREATE INDEX ix_race_result_publication_history_race_created
    ON race_result_publication_history(race_id, created_at DESC);
