CREATE TABLE event_certificate_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    enabled BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_event_certificate_settings_event UNIQUE (event_id)
);

CREATE TABLE event_certificate_allowed_fields (
    settings_id BIGINT NOT NULL REFERENCES event_certificate_settings(id) ON DELETE CASCADE,
    field_name VARCHAR(32) NOT NULL,
    PRIMARY KEY (settings_id, field_name),
    CONSTRAINT ck_event_certificate_allowed_field CHECK (field_name IN (
        'OFFICIAL_TIME', 'GUN_TIME', 'CHIP_TIME', 'OFFICIAL_PLACE',
        'OVERALL_PLACE', 'GENDER_PLACE', 'CATEGORY_PLACE', 'CATEGORY_NAME', 'BIB'
    ))
);

CREATE TABLE certificate_templates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    display_name VARCHAR(255) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    display_order INTEGER NOT NULL DEFAULT 0,
    original_filename VARCHAR(255) NOT NULL,
    storage_provider VARCHAR(32) NOT NULL,
    storage_key VARCHAR(1024) NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    size_bytes BIGINT NOT NULL,
    sha256 VARCHAR(64) NOT NULL,
    uploaded_at TIMESTAMPTZ NOT NULL,
    uploaded_by VARCHAR(160) NOT NULL,
    participant_x NUMERIC(10,2) NOT NULL DEFAULT 72,
    participant_y NUMERIC(10,2) NOT NULL DEFAULT 360,
    participant_width NUMERIC(10,2) NOT NULL DEFAULT 698,
    participant_font_size NUMERIC(6,2) NOT NULL DEFAULT 28,
    participant_min_font_size NUMERIC(6,2) NOT NULL DEFAULT 14,
    participant_alignment VARCHAR(16) NOT NULL DEFAULT 'CENTER',
    event_x NUMERIC(10,2) NOT NULL DEFAULT 72,
    event_y NUMERIC(10,2) NOT NULL DEFAULT 310,
    event_width NUMERIC(10,2) NOT NULL DEFAULT 698,
    event_font_size NUMERIC(6,2) NOT NULL DEFAULT 14,
    event_min_font_size NUMERIC(6,2) NOT NULL DEFAULT 9,
    event_line_spacing NUMERIC(6,2) NOT NULL DEFAULT 18,
    event_alignment VARCHAR(16) NOT NULL DEFAULT 'CENTER',
    dynamic_x NUMERIC(10,2) NOT NULL DEFAULT 150,
    dynamic_y NUMERIC(10,2) NOT NULL DEFAULT 235,
    dynamic_width NUMERIC(10,2) NOT NULL DEFAULT 540,
    dynamic_max_height NUMERIC(10,2) NOT NULL DEFAULT 150,
    dynamic_font_size NUMERIC(6,2) NOT NULL DEFAULT 13,
    dynamic_min_font_size NUMERIC(6,2) NOT NULL DEFAULT 8,
    dynamic_line_spacing NUMERIC(6,2) NOT NULL DEFAULT 18,
    dynamic_alignment VARCHAR(16) NOT NULL DEFAULT 'LEFT',
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_certificate_templates_storage_key UNIQUE (storage_provider, storage_key),
    CONSTRAINT ck_certificate_templates_size CHECK (size_bytes > 0),
    CONSTRAINT ck_certificate_templates_alignment CHECK (
        participant_alignment IN ('LEFT', 'CENTER', 'RIGHT') AND
        event_alignment IN ('LEFT', 'CENTER', 'RIGHT') AND
        dynamic_alignment IN ('LEFT', 'CENTER', 'RIGHT')
    ),
    CONSTRAINT ck_certificate_templates_layout CHECK (
        participant_width > 0 AND participant_font_size > 0 AND participant_min_font_size > 0 AND
        event_width > 0 AND event_font_size > 0 AND event_min_font_size > 0 AND event_line_spacing > 0 AND
        dynamic_width > 0 AND dynamic_max_height > 0 AND dynamic_font_size > 0 AND
        dynamic_min_font_size > 0 AND dynamic_line_spacing > 0
    )
);

CREATE INDEX ix_certificate_templates_event_order
    ON certificate_templates (event_id, display_order, id);

CREATE TABLE certificate_template_races (
    template_id BIGINT NOT NULL REFERENCES certificate_templates(id) ON DELETE CASCADE,
    race_id BIGINT NOT NULL REFERENCES races(id) ON DELETE CASCADE,
    PRIMARY KEY (template_id, race_id)
);

CREATE INDEX ix_certificate_template_races_race
    ON certificate_template_races (race_id, template_id);

