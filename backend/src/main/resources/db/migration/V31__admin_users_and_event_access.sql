CREATE TABLE admin_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(160) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    display_name VARCHAR(255) NOT NULL,
    role VARCHAR(32) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_admin_users_username CHECK (btrim(username) <> ''),
    CONSTRAINT ck_admin_users_display_name CHECK (btrim(display_name) <> ''),
    CONSTRAINT ck_admin_users_role CHECK (role IN ('ORGANIZER', 'TIMEKEEPER'))
);

CREATE UNIQUE INDEX uk_admin_users_username_normalized
    ON admin_users (lower(username));

CREATE INDEX ix_admin_users_role_active
    ON admin_users (role, active);

CREATE TABLE event_user_access (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES admin_users(id) ON DELETE CASCADE,
    event_id BIGINT NOT NULL REFERENCES events(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_event_user_access_user_event UNIQUE (user_id, event_id)
);

CREATE INDEX ix_event_user_access_event_user
    ON event_user_access (event_id, user_id);

ALTER TABLE admin_change_logs
    DROP CONSTRAINT ck_admin_change_logs_entity_type;

ALTER TABLE admin_change_logs
    ADD CONSTRAINT ck_admin_change_logs_entity_type CHECK (
        entity_type IN (
            'REGISTRATION', 'RESULT', 'AWARD_POLICY', 'EVENT_SERIES', 'EVENT',
